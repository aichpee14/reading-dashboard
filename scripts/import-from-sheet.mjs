// One-time importer: pulls the currently-published Google Sheet CSV and emits
// import.sql — grouping session rows into a books catalog + linked sessions.
// Usage: node scripts/import-from-sheet.mjs [csvUrl]   (writes import.sql)
import { writeFileSync } from "node:fs";

const CSV_URL = process.argv[2] ||
  "https://docs.google.com/spreadsheets/d/e/2PACX-1vTBniz9kLARYxnBh-ofky-aAkJX0b1Y_MV3IDXq0ZVrBYxy94IOVVwHGz1fQq55GSY_UhlwyrBnuKx9/pub?gid=0&single=true&output=csv";

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else {
      if (c === '"') inQ = true;
      else if (c === ",") { row.push(field); field = ""; }
      else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
      else if (c === "\r") { /* ignore */ }
      else field += c;
    }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((v) => v.trim() !== ""));
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const qn = (v) => (v === "" || v === null || v === undefined ? "NULL" : String(Number(v)));
const normStatus = (s) => {
  s = String(s || "").trim().toLowerCase();
  return s.includes("finish") ? "finished" : s.includes("dnf") ? "dnf" : "reading";
};

const res = await fetch(CSV_URL);
if (!res.ok) { console.error("fetch failed:", res.status); process.exit(1); }
const rows = parseCsv(await res.text());
if (rows.length < 2) { console.error("no data rows"); process.exit(1); }

const header = rows[0].map((h) => h.trim().toLowerCase());
const idx = (name) => header.indexOf(name);
const col = {
  date: idx("date"),
  title: header.findIndex((h) => ["book title", "title", "book"].includes(h)),
  author: idx("author"),
  genre: idx("genre"),
  pages: header.findIndex((h) => ["pages read", "pages"].includes(h)),
  minutes: header.findIndex((h) => ["minutes read", "minutes"].includes(h)),
  status: idx("status"),
  rating: idx("rating"),
  total: header.findIndex((h) => ["total pages", "book length"].includes(h)),
  cover: header.findIndex((h) => ["cover url", "cover image", "cover"].includes(h)),
};
const get = (r, i) => (i >= 0 && i < r.length ? r[i].trim() : "");

// Group sessions into books keyed by title.
const books = new Map(); // title -> {id, author, genre, total, statuses:Set, rating, cover, sessions:[]}
let nextId = 1;
for (const r of rows.slice(1)) {
  const date = get(r, col.date);
  const title = get(r, col.title);
  if (!date || !title) continue;
  if (!books.has(title)) {
    books.set(title, { id: nextId++, author: "", genre: "", total: "", statuses: new Set(), rating: "", cover: "", sessions: [] });
  }
  const b = books.get(title);
  if (get(r, col.author)) b.author = get(r, col.author);
  if (get(r, col.genre)) b.genre = get(r, col.genre);
  if (get(r, col.total)) b.total = get(r, col.total);
  if (get(r, col.cover)) b.cover = get(r, col.cover);
  const st = normStatus(get(r, col.status));
  b.statuses.add(st);
  const rating = get(r, col.rating);
  if (rating) b.rating = rating; // last non-empty rating (usually on the finished row)
  b.sessions.push({ date: date.slice(0, 10), pages: get(r, col.pages) || 0, minutes: get(r, col.minutes) || 0 });
}

const bookStatus = (statuses) => statuses.has("finished") ? "finished" : statuses.has("dnf") ? "dnf" : "reading";

const lines = ["-- generated by import-from-sheet.mjs"];
for (const [title, b] of books) {
  lines.push(
    `INSERT INTO books (id,title,author,genre,total_pages,status,rating,cover_url) VALUES (` +
    [b.id, q(title), q(b.author), q(b.genre || "Unspecified"), qn(b.total), q(bookStatus(b.statuses)), qn(b.rating), q(b.cover)].join(",") + ");"
  );
}
let sessionCount = 0;
for (const [, b] of books) {
  for (const s of b.sessions) {
    lines.push(
      `INSERT INTO entries (book_id,date,pages_read,minutes_read) VALUES (` +
      [b.id, q(s.date), qn(s.pages), qn(s.minutes)].join(",") + ");"
    );
    sessionCount++;
  }
}
writeFileSync("import.sql", lines.join("\n") + "\n");
console.error(`wrote import.sql: ${books.size} books, ${sessionCount} sessions`);
